    public Main() {
        initComponents();
        studentService = new StudentService();
        students = new ArrayList<Student>();
        String message = "";
        try{
            List<String> studentsOfFile = studentService.getAllRowsFromFile();
            
            for(var studentString : studentsOfFile){
                String[] studentProperties = studentString.split("\\|");
                
                Student student = new Student();
                
                student.setId(Long.parseLong(studentProperties[0]));
                student.setName(studentProperties[1]);
                student.setLastName(studentProperties[2]);
                
                students.add(student);
                
                message += student+"\n";
            }
            
            this.txtAllRecords.setText(message);
            studentService.saveAllStudentsJson(students);
            
        }catch(Exception exe){
            System.out.println(exe.getMessage());
        }
        
        
    }

